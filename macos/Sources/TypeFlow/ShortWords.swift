import Foundation

/// Компактный bundled-список ЧАСТЫХ коротких (2-буквенных) слов — позитивный сигнал
/// для авто-конвертации коротких слов (3.1, issue #22 «Не могу» → «Yt могу»).
///
/// Зачем отдельный список, а не NSSpellChecker: на длине 2 системный словарь
/// принимает почти любой набор букв за «слово», поэтому обычная двусторонняя проверка
/// ненадёжна — ради этого в детекторе и стоял гейт `count >= 3`. Здесь мы разрешаем
/// ровно двухбуквенные слова, но ТОЛЬКО когда их конверсия попадает в этот выверенный
/// список частотных слов (строго позитивный сигнал, как у иврит-ветки детектора).
///
/// Безопасность (аудит ПОЛНОГО набора прообразов, scripts/audit_short.py — проверяет не
/// топ-N корпуса, а каждый 2-буквенный образ обоих списков):
///   • коллизий «частое ↔ частое» между ru и en НЕТ;
///   • реальные англ. токены/аббревиатуры, чей раскладочный образ попадает в ru-список
///     (vs→«мы», dj→«во», kb→«ли», bp→«из»), внесены в en-список —
///     тогда они «в обоих списках», и симметричный гейт .keep отклоняет их авто-конверсию
///     в ОБЕ стороны (ручной триггер по-прежнему работает). Так «Spain vs Italy» не станет
///     «Spain мы Italy» (skeptic-находка 3.1.0), а точность сохраняется важнее полноты.
///   • lowercase `ye` и `jr` — сознательные пользовательские исключения: в рабочем
///     RU-контексте они должны превращаться в частые «ну» и «ок», несмотря на редкие
///     английские `ye` и инициалы/сокращение `jr`.
/// Список закрыт относительно этих коллизий: добавление слова в один список требует, чтобы
/// его прообраз в другой раскладке тоже был в списке (иначе новая ложная конверсия) — все
/// добавленные en-токены имеют ru-прообраз, уже присутствующий в ru-списке.
/// Языки без списка сюда не попадают — их 2-буквенные слова авто-путём не трогаются.
/// Слова только в нижнем регистре; сравнение — по `lowercased()`.
enum ShortWords {
    private static let ru: Set<String> = [
        "не", "ты", "на", "он", "мы", "вы", "да", "но", "за", "бы", "же", "из",
        "ну", "по", "то", "от", "их", "ее", "её", "со", "ли", "ни", "об", "ей",
        "во", "им", "ко", "те", "та", "уж", "ок", "эй", "го",
    ]
    private static let en: Set<String> = [
        "to", "it", "of", "is", "in", "we", "me", "he", "my", "on", "do", "no",
        "be", "so", "go", "if", "up", "at", "as", "an", "us", "or", "by", "am",
        "ok", "hi", "oh", "ah", "um", "mr", "ya",
        // Отклоняемые неоднозначные (реальные en-токены, образ = частое ru-слово):
        // vs→«мы» dj→«во» kb→«ли» bp→«из» ds→«вы».
        "vs", "dj", "kb", "bp", "ds",
    ]

    /// Набор частотных коротких слов для языка (по 2-буквенному коду), либо nil,
    /// если для языка список не предусмотрен.
    static func common(_ lang: String) -> Set<String>? {
        switch String(lang.prefix(2)) {
        case "ru": return ru
        case "en": return en
        default:   return nil
        }
    }
}
